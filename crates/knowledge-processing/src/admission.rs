//! Host binding onto the one process account.
//!
//! Charges stay distinct. They become [`knowledge_core::jobs::Reservation`] values
//! for that account. They do not redefine [`knowledge_core::backend::Budget::max_memory_bytes`].
//! No queue, registry, or source digest is created here.

use std::cell::Cell;
use std::fmt;
use std::time::Instant;

use knowledge_core::jobs::Reservation;

/// One effect cost. Input, work, output, and live memory are separate charges.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Charge {
    /// Bytes about to be read from an admitted source or archive member.
    Input { bytes: u64 },
    /// Estimated parser or decompression allocation before that allocation.
    Work { bytes: u64 },
    /// Derived text or preview about to be retained.
    Output { bytes: u64 },
    /// Child, model, runtime, or retained transcript cost while it stays live.
    Live { bytes: u64 },
    /// Generated bytes about to be written. Reserve this before creating the file.
    Storage { bytes: u64 },
}

impl Charge {
    /// Byte count carried by this charge.
    pub fn bytes(self) -> u64 {
        match self {
            Self::Input { bytes }
            | Self::Work { bytes }
            | Self::Output { bytes }
            | Self::Live { bytes }
            | Self::Storage { bytes } => bytes,
        }
    }

    /// Generated-storage charges use the account's temporary-byte promise.
    pub fn is_storage(self) -> bool {
        matches!(self, Self::Storage { .. })
    }
}

/// Map one charge onto the existing jobs reservation. Storage is not memory.
pub fn reservation(charge: Charge) -> Reservation {
    if charge.is_storage() {
        Reservation {
            memory_bytes: 0,
            temporary_bytes: charge.bytes(),
        }
    } else {
        Reservation {
            memory_bytes: charge.bytes(),
            temporary_bytes: 0,
        }
    }
}

/// Refusal from the shared account. Processing does not retry or spin.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum AdmitError {
    /// The need exceeds the whole memory ceiling the host enforces.
    TooLargeMemory,
    /// The need exceeds the whole generated-storage ceiling the host enforces.
    TooLargeStorage,
    /// Current memory promises block this charge. The caller keeps its queue.
    WaitingMemory,
    /// Current storage promises block this charge. The caller keeps its queue.
    WaitingStorage,
    /// The host cancelled further work.
    Cancelled,
    /// The host deadline has passed.
    Deadline,
    /// This thread already has an account binding.
    Busy,
}

impl fmt::Display for AdmitError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        let text = match self {
            Self::TooLargeMemory => "processing admission: memory need exceeds the shared account",
            Self::TooLargeStorage => {
                "processing admission: storage need exceeds the shared account"
            }
            Self::WaitingMemory => "processing admission: waiting for memory",
            Self::WaitingStorage => "processing admission: waiting for storage",
            Self::Cancelled => "processing admission: cancelled",
            Self::Deadline => "processing admission: deadline",
            Self::Busy => "processing admission: an account is already bound on this thread",
        };
        formatter.write_str(text)
    }
}

impl std::error::Error for AdmitError {}

/// Host-supplied account. Implement this by reserving on the process account.
///
/// Store every acquired holding for the whole call. Finish those holdings only
/// after this call returns; child workers are already waited inside the call.
/// Dropping a holding does not release its charge.
pub trait SharedAccount {
    /// Reserve `charge` before the corresponding effect.
    fn reserve(&mut self, charge: Charge) -> Result<(), AdmitError>;

    /// True when further work must stop.
    fn cancelled(&self) -> bool {
        false
    }
}

/// Optional child and deadline facts for one admitted call.
#[derive(Clone, Copy, Debug, Default)]
pub struct Bound {
    /// Resident-set ceiling for each owned child, in bytes.
    /// `None` does not invent a ceiling.
    pub child_rss_bytes: Option<u64>,
    /// Generated-storage promise charged once before owned media writes.
    /// `None` does not invent a storage ceiling.
    pub storage_bytes: Option<u64>,
    /// Absolute monotonic deadline. `None` keeps each worker's own timeout.
    pub deadline: Option<Instant>,
}

struct Legacy {
    limit: Option<u64>,
}

impl SharedAccount for Legacy {
    fn reserve(&mut self, charge: Charge) -> Result<(), AdmitError> {
        if self.limit.is_some_and(|limit| charge.bytes() > limit) {
            return Err(if charge.is_storage() {
                AdmitError::TooLargeStorage
            } else {
                AdmitError::TooLargeMemory
            });
        }
        Ok(())
    }
}

struct Slot {
    data: *mut (),
    reserve: fn(*mut (), Charge) -> Result<(), AdmitError>,
    cancelled: fn(*mut ()) -> bool,
    child_rss_bytes: Option<u64>,
    storage_bytes: Option<u64>,
    deadline: Option<Instant>,
}

thread_local! {
    static SLOT: Cell<*const Slot> = const { Cell::new(std::ptr::null()) };
}

fn reserve_raw<T: SharedAccount>(data: *mut (), charge: Charge) -> Result<(), AdmitError> {
    // SAFETY: `data` points at the account passed to `with_host` on this thread.
    // The guard clears the slot before that borrow ends, and effects run synchronously.
    let account = unsafe { &mut *data.cast::<T>() };
    account.reserve(charge)
}

fn cancelled_raw<T: SharedAccount>(data: *mut ()) -> bool {
    // SAFETY: same binding lifetime as `reserve_raw`.
    let account = unsafe { &*data.cast::<T>() };
    account.cancelled()
}

struct Clear;

impl Drop for Clear {
    fn drop(&mut self) {
        SLOT.with(|slot| slot.set(std::ptr::null()));
    }
}

fn current() -> Option<*const Slot> {
    let pointer = SLOT.with(|slot| slot.get());
    if pointer.is_null() {
        None
    } else {
        Some(pointer)
    }
}

fn install<T: SharedAccount, R>(account: &mut T, bound: Bound, body: impl FnOnce() -> R) -> R {
    let slot = Slot {
        data: std::ptr::from_mut::<T>(account).cast::<()>(),
        reserve: reserve_raw::<T>,
        cancelled: cancelled_raw::<T>,
        child_rss_bytes: bound.child_rss_bytes,
        storage_bytes: bound.storage_bytes,
        deadline: bound.deadline,
    };
    SLOT.with(|current_slot| current_slot.set(&slot));
    let _clear = Clear;
    body()
}

/// Bind `account` for the synchronous body on this thread.
pub fn with_host<T: SharedAccount, R>(
    account: &mut T,
    bound: Bound,
    body: impl FnOnce() -> R,
) -> Result<R, AdmitError> {
    if current().is_some() {
        return Err(AdmitError::Busy);
    }
    Ok(install(account, bound, body))
}

/// Direct-library bypass. A charge above `limit` is refused. `None` adds no ceiling.
pub fn with_legacy<R>(limit: Option<u64>, body: impl FnOnce() -> R) -> R {
    if current().is_some() {
        return body();
    }
    let mut account = Legacy { limit };
    install(&mut account, Bound::default(), body)
}

/// Stop when the host cancelled the call or its deadline has passed.
pub fn checkpoint() -> Result<(), AdmitError> {
    let Some(pointer) = current() else {
        return Err(AdmitError::Busy);
    };
    // SAFETY: the installing `with_host` frame is still on this thread's stack.
    let slot = unsafe { &*pointer };
    if (slot.cancelled)(slot.data) {
        return Err(AdmitError::Cancelled);
    }
    if slot
        .deadline
        .is_some_and(|deadline| Instant::now() >= deadline)
    {
        return Err(AdmitError::Deadline);
    }
    Ok(())
}

/// Reserve one charge on the bound account before the effect.
pub fn before(charge: Charge) -> Result<(), AdmitError> {
    if charge.bytes() == 0 {
        return Ok(());
    }
    let Some(pointer) = current() else {
        return Err(AdmitError::Busy);
    };
    // SAFETY: the installing `with_host` frame is still on this thread's stack.
    let slot = unsafe { &*pointer };
    (slot.reserve)(slot.data, charge)
}

/// Resident ceiling for an owned child. `None` means the host admitted no child ceiling.
pub fn child_rss_bytes() -> Option<u64> {
    let pointer = current()?;
    // SAFETY: the installing `with_host` frame is still on this thread's stack.
    let slot = unsafe { &*pointer };
    slot.child_rss_bytes
}

/// Generated-storage promise for this binding, when the host supplied one.
pub fn storage_bytes() -> Option<u64> {
    let pointer = current()?;
    // SAFETY: the installing `with_host` frame is still on this thread's stack.
    let slot = unsafe { &*pointer };
    slot.storage_bytes
}

/// Host deadline, when the binding supplied one.
pub fn deadline() -> Option<Instant> {
    let pointer = current()?;
    // SAFETY: the installing `with_host` frame is still on this thread's stack.
    let slot = unsafe { &*pointer };
    slot.deadline
}

/// True when an [`AdmitError`] or [`crate::WorkerFailure`] must not become coverage.
pub fn stops_call(error: &anyhow::Error) -> bool {
    error.chain().any(|item| {
        item.downcast_ref::<AdmitError>().is_some()
            || item.downcast_ref::<crate::WorkerFailure>().is_some()
    })
}
