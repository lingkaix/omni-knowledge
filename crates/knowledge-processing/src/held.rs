/// Borrowed actual regular source and expected SHA-256 data, never a permission capability.
#[derive(Clone, Copy)]
pub struct HeldSource<'a> {
    /// Already selected native source; the caller excludes concurrent mutation and cursor use.
    pub file: &'a File,
    /// Expected version from the native owner's actual verification, not a processing-created key.
    pub expected_version: &'a ContentDigest,
}

/// A publication member explicitly selected by the native owner.
pub struct EpubMember<'a> {
    /// Source bytes and version; logical names never locate a source on the host filesystem.
    pub source: HeldSource<'a>,
    /// Normal relative publication name.
    /// The `EpubMember` slice order is the page order. This name is only the link-lookup key.
    pub logical_name: &'a RelativePath,
}

/// A real exclusively created artifact relative to the retained private directory.
#[derive(Debug)]
pub struct NativeArtifact {
    /// Logical relative name, not a cleanup or publication grant.
    pub name: String,
    /// Actual generated regular inode; callers consume this FD, not a pathname reopen.
    pub file: File,
}

/// Completed EPUB bytes and source pins retained until native publication or retirement.
#[derive(Debug)]
pub struct HeldEpub {
    /// Native-owner-created private output inode, duplicated without a pathname lookup.
    pub file: File,
    /// Number of actual encoded chapters.
    pub chapters: usize,
    /// Actual selected sources, retained through the caller's consumer/publication lifetime.
    pub sources: Vec<File>,
}

/// One actual converted clip and its original recording-clock interval.
#[derive(Debug)]
pub struct HeldMediaSegment {
    /// Inclusive source position in seconds.
    pub start_seconds: f64,
    /// Exclusive source position in seconds.
    pub end_seconds: f64,
    /// Actual generated bytes and logical relative name.
    pub artifact: NativeArtifact,
}

/// Native output records and FD leases, not installed user-visible files.
#[derive(Debug)]
pub struct HeldVideo {
    /// Actual selected private directory, immune to ancestor/path replacement.
    pub directory: File,
    /// Actual selected source retained with the outputs.
    pub source: File,
    /// Completed clips in source-clock order.
    pub segments: Vec<HeldMediaSegment>,
}

/// A settled failure retains known partial artifacts for the native owner's inspection and cleanup.
/// Drop records before finishing `retained`; no implicit removal or publication occurs.
pub struct PartialOutputs {
    /// Original failure; an empty artifact list does not imply success.
    pub cause: anyhow::Error,
    /// Actual private directory, if this call creates relative artifacts.
    pub directory: Option<File>,
    /// Known stopped outputs; `epub` labels the supplied output FD and is not a host name.
    pub artifacts: Vec<NativeArtifact>,
    /// Actual source pins.
    pub sources: Vec<File>,
    /// Live record/storage capabilities from the original account or claim.
    pub retained: Vec<Holding>,
}
impl std::fmt::Debug for PartialOutputs {
    /// Show only ownership counts, not source contents or child diagnostics.
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("PartialOutputs")
            .field("artifacts", &self.artifacts.len())
            .field("sources", &self.sources.len())
            .finish_non_exhaustive()
    }
}
impl std::fmt::Display for PartialOutputs {
    /// Report a typed failed result without exposing source names or child diagnostics.
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("held-descriptor processing failed; stopped private artifacts retained")
    }
}
impl std::error::Error for PartialOutputs {
    /// Preserve the original failure for typed triage.
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        Some(self.cause.as_ref())
    }
}

/// Expected source bytes did not match, or changed during an actual descriptor read/execution.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct SourceChanged;
impl std::fmt::Display for SourceChanged {
    /// Stable classification without source data.
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("held source version changed")
    }
}
impl std::error::Error for SourceChanged {}

/// Native before/after identity and byte-change observation, not source-admission authority.
#[derive(Clone, Copy, PartialEq, Eq)]
pub(crate) struct Stamp(u64, u64, u64, i64, i64, i64, i64);
impl Stamp {
    /// Sample the actual regular inode; reject devices, directories and nonseekable streams.
    pub(crate) fn read(file: &File) -> Result<Self> {
        let m = file.metadata()?;
        ensure!(m.is_file(), "Held source must be a regular seekable file");
        Ok(Self(
            m.dev(),
            m.ino(),
            m.len(),
            m.mtime(),
            m.mtime_nsec(),
            m.ctime(),
            m.ctime_nsec(),
        ))
    }
}

/// Hash bounded `pread` batches only inside the watched worker; the descriptor cursor is unchanged.
fn verify(source: HeldSource<'_>) -> Result<Stamp> {
    let before = Stamp::read(source.file)?;
    let mut hash = Sha256::new();
    let mut buffer = [0u8; 64 * 1024];
    let mut offset = 0;
    loop {
        let length = match source.file.read_at(&mut buffer, offset) {
            Ok(length) => length,
            Err(error) if error.kind() == io::ErrorKind::Interrupted => continue,
            Err(error) => return Err(error.into()),
        };
        if length == 0 {
            break;
        }
        hash.update(&buffer[..length]);
        offset += length as u64;
        // A growing source cannot turn verification into an unbounded read.
        ensure!(offset <= before.2, SourceChanged);
    }
    ensure!(Stamp::read(source.file)? == before, SourceChanged);
    ensure!(
        format!("{:x}", hash.finalize()) == source.expected_version.as_str(),
        SourceChanged
    );
    Ok(before)
}

/// Check a newly created private regular output without changing permissions or truncating it.
fn private_file(file: &File) -> Result<()> {
    let m = file.metadata()?;
    ensure!(
        m.is_file() && m.len() == 0 && m.nlink() == 1,
        "Output must be a new empty private regular file"
    );
    ensure!(
        m.uid() == unsafe { libc::geteuid() } && m.mode() & 0o077 == 0,
        "Output is not private to this native owner"
    );
    // SAFETY: inspection only, on a caller-owned live descriptor.
    let flags = unsafe { libc::fcntl(file.as_raw_fd(), libc::F_GETFL) };
    ensure!(
        flags >= 0 && flags & libc::O_APPEND == 0 && flags & libc::O_ACCMODE != libc::O_RDONLY,
        "Output descriptor must be writable without append"
    );
    selected_volume(file)?;
    Ok(())
}

/// Validate actual directory facts; native policy/placement/private-namespace qualification remains with the caller.
fn private_directory(file: &File) -> Result<()> {
    let m = file.metadata()?;
    ensure!(
        m.is_dir() && m.uid() == unsafe { libc::geteuid() } && m.mode() & 0o077 == 0,
        "Output directory must be native-owned and private"
    );
    selected_volume(file)?;
    Ok(())
}

/// Inherit only these already owned descriptors, changing flags/CWD only after fork in the child.
/// The parent must retain every exact descriptor until the runner establishes collection.
fn inherit(
    command: &mut Command,
    files: &[&File],
    directory: Option<&File>,
    rewind: Option<&File>,
) {
    let descriptors: Vec<_> = files.iter().map(|file| file.as_raw_fd()).collect();
    let directory = directory.map(AsRawFd::as_raw_fd);
    let rewind = rewind.map(AsRawFd::as_raw_fd);
    inherit_raw(command, descriptors, directory, rewind);
}

/// Install one child-only descriptor/CWD setup for both verification and actual encoding protocols.
fn inherit_raw(
    command: &mut Command,
    descriptors: Vec<i32>,
    directory: Option<i32>,
    rewind: Option<i32>,
) {
    // SAFETY: only async-signal-safe descriptor operations run after fork; no allocation or locks.
    unsafe {
        command.pre_exec(move || {
            for fd in &descriptors {
                let flags = libc::fcntl(*fd, libc::F_GETFD);
                if flags < 0 || libc::fcntl(*fd, libc::F_SETFD, flags & !libc::FD_CLOEXEC) < 0 {
                    return Err(io::Error::last_os_error());
                }
            }
            if let Some(fd) = directory
                && libc::fchdir(fd) != 0
            {
                return Err(io::Error::last_os_error());
            }
            if let Some(fd) = rewind
                && libc::lseek(fd, 0, libc::SEEK_SET) < 0
            {
                return Err(io::Error::last_os_error());
            }
            Ok(())
        });
    }
}

/// Create only a generated flat constant name relative to the selected directory, never through an ancestor path.
fn create(directory: &File, name: &str) -> Result<File> {
    let name = std::ffi::CString::new(name)?;
    // SAFETY: live directory and NUL-terminated generated name; exclusive no-follow regular creation.
    let fd = unsafe {
        libc::openat(
            directory.as_raw_fd(),
            name.as_ptr(),
            libc::O_CREAT | libc::O_EXCL | libc::O_NOFOLLOW | libc::O_RDWR | libc::O_CLOEXEC,
            0o600,
        )
    };
    if fd < 0 {
        return Err(io::Error::last_os_error().into());
    }
    // SAFETY: this call uniquely owns the successfully created descriptor.
    let file = unsafe { File::from_raw_fd(fd) };
    private_file(&file)?;
    Ok(file)
}

/// Preserve actual resources in the existing unknown-worker/write owner, or return typed stopped partials.
fn failed(
    mut cause: anyhow::Error,
    directory: Option<File>,
    artifacts: Vec<NativeArtifact>,
    sources: Vec<File>,
    credits: &mut Credits,
) -> anyhow::Error {
    let mut retained = credits.retained();
    if let Some(holding) = credits.storage.0.take() {
        retained.push(holding);
    }
    if let Some(pending) = cause.downcast_mut::<UnsettledChild>() {
        for file in sources.into_iter().chain(directory) {
            pending.retain_descriptor(file);
        }
        for artifact in artifacts {
            pending.retain_artifact(artifact.name.into());
            pending.retain_descriptor(artifact.file);
        }
        for holding in retained {
            pending.retain_holding(holding);
        }
        return cause;
    }
    if let Some(pending) = cause.downcast_mut::<UnsettledWrite>() {
        pending.leases.extend(sources.into_iter().chain(directory));
        for artifact in artifacts {
            pending.artifacts.push(artifact.name.into());
            pending.leases.push(artifact.file);
        }
        pending.retained.extend(retained);
        return cause;
    }
    anyhow::Error::new(PartialOutputs {
        cause,
        directory,
        artifacts,
        sources,
        retained,
    })
}

/// Retain output-record and unused storage credit through native publication/retirement.
fn retained(credits: &mut Credits) -> Vec<Holding> {
    let mut result = credits.retained();
    if let Some(holding) = credits.storage.0.take() {
        result.push(holding);
    }
    result
}

/// Child-only descriptor manifest; logical names are data, never filesystem lookup instructions.
#[derive(Serialize, Deserialize)]
#[doc(hidden)]
pub struct ExportWire {
    /// Publication title.
    pub title: String,
    /// Include only explicitly selected referenced media.
    pub include_media: bool,
    /// Exact inherited source descriptors and expected versions.
    pub members: Vec<WireMember>,
}
/// One inherited descriptor in the actual parser protocol.
#[derive(Serialize, Deserialize)]
#[doc(hidden)]
pub struct WireMember {
    /// Child-visible actual FD, pinned by the parent until collection.
    pub fd: i32,
    /// Logical publication name.
    pub name: RelativePath,
    /// Expected source bytes.
    pub version: ContentDigest,
}

/// Encode selected held members into a native-owner-created empty private output file.
/// Complete transport, metadata, source pins, child RSS and extent credit precede serialization or execution.
/// Returns live output/source leases and holdings; stopped partials and unknown owners retain actual FDs.
/// The native caller still supplies current policy, owner intent, source admission and final publication.
pub fn export_epub_held_funded(
    members: &[EpubMember<'_>],
    output: &File,
    title: &str,
    include_media: bool,
    child_rss: Option<u64>,
    storage_bytes: u64,
    funding: &mut Funding<'_>,
) -> Result<Admitted<HeldEpub>> {
    funding.checkpoint()?;
    ensure!(!title.trim().is_empty(), "EPUB title must not be empty");
    ensure!(
        storage_bytes > 0,
        "Generated storage promise must be positive"
    );
    private_file(output)?;
    let mut size = title
        .len()
        .checked_mul(6)
        .context("EPUB manifest overflow")? as u64
        + 1024;
    for member in members {
        Stamp::read(member.source.file)?;
        size = size
            .checked_add((member.logical_name.as_str().len() as u64).saturating_mul(6) + 1024)
            .context("EPUB manifest overflow")?;
    }
    // Simultaneous typed manifest, serialized bytes, descriptor arrays and result/source records.
    let mut credits = Credits::new(
        funding,
        size.checked_mul(4).context("EPUB metadata overflow")?,
        size,
        crate::opaque::capture_memory(1024),
        child_rss,
        storage_bytes,
    )?;
    let sources: Vec<_> = members
        .iter()
        .map(|member| member.source.file.try_clone())
        .collect::<io::Result<_>>()?;
    let destination = output.try_clone()?;
    let mut artifacts = vec![NativeArtifact {
        name: "epub".into(),
        file: destination,
    }];
    let result = (|| {
        let stamps: Vec<_> = members
            .iter()
            .map(|member| Stamp::read(member.source.file))
            .collect::<Result<_>>()?;
        verify_in_worker(
            sources
                .iter()
                .zip(members.iter().map(|member| member.source.expected_version)),
            &mut credits,
            funding,
        )?;
        let wire = ExportWire {
            title: title.to_owned(),
            include_media,
            members: members
                .iter()
                .zip(&sources)
                .map(|(member, file)| WireMember {
                    fd: file.as_raw_fd(),
                    name: member.logical_name.clone(),
                    version: member.source.expected_version.clone(),
                })
                .collect(),
        };
        let bytes = serde_json::to_vec(&wire)?;
        let mut command = Command::new(worker::parser_worker_path()?);
        command.args([
            "export-epub-held",
            &artifacts[0].file.as_raw_fd().to_string(),
        ]);
        let mut files: Vec<_> = sources.iter().collect();
        files.push(&artifacts[0].file);
        inherit(&mut command, &files, None, None);
        let generated = worker::run(
            command,
            Some(&bytes),
            1024,
            Duration::from_secs(300),
            &mut credits,
            funding,
            Some(storage_bytes),
        );
        // Reconciliation must not inspect or release an unknown writer.
        if generated
            .as_ref()
            .is_err_and(|error| error.downcast_ref::<UnsettledChild>().is_some())
        {
            return generated.map(|_| 0);
        }
        let artifact = artifacts.pop().context("Missing EPUB output")?;
        let (length, file) =
            crate::funding::reconcile_file(artifact.file, &mut credits.storage, &[])?;
        artifacts.push(NativeArtifact {
            name: artifact.name,
            file,
        });
        let capture = generated?;
        ensure!(length > 0, "EPUB worker produced empty output");
        verify_in_worker(
            sources
                .iter()
                .zip(members.iter().map(|member| member.source.expected_version)),
            &mut credits,
            funding,
        )?;
        for (member, stamp) in members.iter().zip(stamps) {
            ensure!(Stamp::read(member.source.file)? == stamp, SourceChanged);
        }
        let count = std::str::from_utf8(&capture.bytes)?
            .trim()
            .parse::<usize>()?;
        artifacts[0].file.sync_all()?;
        Ok(count)
    })();
    match result {
        Ok(chapters) => Ok(Admitted {
            value: HeldEpub {
                file: artifacts.remove(0).file,
                chapters,
                sources,
            },
            retained: retained(&mut credits),
        }),
        Err(error) => Err(failed(error, None, artifacts, sources, &mut credits)),
    }
}

/// Segment the actual held seekable source into exclusive files relative to a native private directory FD.
/// Uses FFmpeg's seekable `fd` protocol, an inherited CWD, and the existing watched worker, not pipes or path grants.
/// Callers exclude concurrent source cursor use; each collected invocation restores its prior cursor.
/// Returns actual artifacts and pins; partial/unknown results retain the same native directory and source.
pub fn segment_video_held_funded(
    source: HeldSource<'_>,
    output_directory: &File,
    seconds: f64,
    plan: ClipPlan,
    funding: &mut Funding<'_>,
) -> Result<Admitted<HeldVideo>> {
    funding.checkpoint()?;
    ensure!(
        seconds.is_finite() && (0.1..=600.0).contains(&seconds),
        "Video segment duration must be from 0.1 through 600 seconds"
    );
    ensure!(
        plan.max_segments > 0 && plan.max_segments <= crate::media::MAX_SEGMENTS,
        "Invalid clip count bound"
    );
    ensure!(
        plan.storage_bytes > 0,
        "Generated storage promise must be positive"
    );
    Stamp::read(source.file)?;
    private_directory(output_directory)?;
    let records = (plan.max_segments as u64)
        .checked_mul(512)
        .and_then(|n| n.checked_add(4096))
        .context("Clip record bound overflow")?;
    let mut credits = Credits::new(
        funding,
        4096,
        records,
        crate::opaque::capture_memory(1024 * 1024),
        plan.child_rss_bytes,
        plan.storage_bytes,
    )?;
    let file = source.file.try_clone()?;
    let directory = output_directory.try_clone()?;
    let mut artifacts = Vec::with_capacity(plan.max_segments);
    let mut ranges = Vec::with_capacity(plan.max_segments);
    let result = (|| {
        let stamp = Stamp::read(source.file)?;
        verify_in_worker(
            std::iter::once((&file, source.expected_version)),
            &mut credits,
            funding,
        )?;
        let mut probe = crate::media::media_command(RuntimeTool::FFprobe)?;
        probe.args([
            "-v",
            "error",
            "-protocol_whitelist",
            "fd",
            "-fd",
            &file.as_raw_fd().to_string(),
            "-i",
            "fd:",
            "-show_entries",
            "format=duration",
            "-of",
            "default=noprint_wrappers=1:nokey=1",
        ]);
        let capture = run_media(
            probe,
            &file,
            &directory,
            None,
            Duration::from_secs(30),
            &mut credits,
            funding,
            None,
        )?;
        let duration: f64 = std::str::from_utf8(&capture.bytes)?.trim().parse()?;
        drop(capture);
        ensure!(
            duration.is_finite() && duration > 0.0,
            "Video duration must be positive"
        );
        let count = (duration / seconds).ceil() as usize;
        ensure!(
            count <= plan.max_segments,
            "Video requires more than the admitted segment count"
        );
        for index in 0..count {
            funding.checkpoint()?;
            let start = index as f64 * seconds;
            let end = (start + seconds).min(duration);
            let name = format!("segment-{index:06}.mp4");
            let destination = create(&directory, &name)?;
            artifacts.push(NativeArtifact {
                name,
                file: destination,
            });
            let destination = &artifacts.last().context("Missing clip output")?.file;
            let limit = credits
                .storage
                .0
                .as_ref()
                .context("Missing generated storage promise")?
                .remaining()?
                .temporary_bytes;
            let mut command = crate::media::media_command(RuntimeTool::FFmpeg)?;
            command.args([
                "-nostdin",
                "-v",
                "error",
                "-ss",
                &format!("{start:.6}"),
                "-protocol_whitelist",
                "fd",
                "-fd",
                &file.as_raw_fd().to_string(),
                "-i",
                "fd:",
            ]);
            crate::media::clip_encoding(&mut command, end - start);
            command.args(["-fd", &destination.as_raw_fd().to_string(), "fd:"]);
            let converted = run_media(
                command,
                &file,
                &directory,
                Some(destination),
                Duration::from_secs(120),
                &mut credits,
                funding,
                Some(limit),
            );
            if converted
                .as_ref()
                .is_err_and(|error| error.downcast_ref::<UnsettledChild>().is_some())
            {
                return converted.map(|_| ());
            }
            let artifact = artifacts.pop().context("Missing clip output")?;
            let (length, file) = crate::funding::reconcile_file(
                artifact.file,
                &mut credits.storage,
                &[Path::new(&artifact.name)],
            )?;
            artifacts.push(NativeArtifact {
                name: artifact.name,
                file,
            });
            converted?;
            ensure!(length > 0, "FFmpeg produced an empty video clip");
            ranges.push((start, end));
            ensure!(Stamp::read(source.file)? == stamp, SourceChanged);
        }
        verify_in_worker(
            std::iter::once((&file, source.expected_version)),
            &mut credits,
            funding,
        )?;
        ensure!(Stamp::read(source.file)? == stamp, SourceChanged);
        Ok(())
    })();
    match result {
        Ok(()) => {
            let segments = ranges
                .into_iter()
                .zip(artifacts)
                .map(
                    |((start_seconds, end_seconds), artifact)| HeldMediaSegment {
                        start_seconds,
                        end_seconds,
                        artifact,
                    },
                )
                .collect();
            Ok(Admitted {
                value: HeldVideo {
                    directory,
                    source: file,
                    segments,
                },
                retained: retained(&mut credits),
            })
        }
        Err(error) => Err(failed(
            error,
            Some(directory),
            artifacts,
            vec![file],
            &mut credits,
        )),
    }
}

/// Execute one real seekable-FD media job and restore its shared cursor only after actual collection.
#[allow(clippy::too_many_arguments)]
fn run_media(
    mut command: Command,
    source: &File,
    directory: &File,
    output: Option<&File>,
    timeout: Duration,
    credits: &mut Credits,
    funding: &Funding<'_>,
    limit: Option<u64>,
) -> Result<worker::Capture> {
    // SAFETY: live regular descriptor; caller serializes concurrent cursor access.
    let cursor = unsafe { libc::lseek(source.as_raw_fd(), 0, libc::SEEK_CUR) };
    ensure!(cursor >= 0, "Source is not seekable");
    let mut files = vec![source, directory];
    files.extend(output);
    inherit(&mut command, &files, Some(directory), Some(source));
    let result = worker::run(command, None, 1024 * 1024, timeout, credits, funding, limit);
    if !result
        .as_ref()
        .is_err_and(|error| error.downcast_ref::<UnsettledChild>().is_some())
    {
        // SAFETY: no owned child/I/O still uses this descriptor after real collection.
        let restored = unsafe { libc::lseek(source.as_raw_fd(), cursor, libc::SEEK_SET) };
        ensure!(restored == cursor, "Cannot restore collected source cursor");
    }
    result
}

/// Run potentially blocking source reads in the same actual watched parser, not the parent I/O loop.
fn verify_in_worker<'a>(
    members: impl Iterator<Item = (&'a File, &'a ContentDigest)>,
    credits: &mut Credits,
    funding: &Funding<'_>,
) -> Result<()> {
    let members: Vec<_> = members
        .enumerate()
        .map(|(index, (file, version))| {
            Ok(WireMember {
                fd: file.as_raw_fd(),
                name: RelativePath::new(index.to_string())?,
                version: version.clone(),
            })
        })
        .collect::<Result<_>>()?;
    let bytes = serde_json::to_vec(&members)?;
    let mut command = Command::new(worker::parser_worker_path()?);
    command.arg("verify-held");
    // All numbers refer to live operation-owned pins, retained by the native error owner if collection is unknown.
    let descriptors: Vec<_> = members.iter().map(|member| member.fd).collect();
    inherit_raw(&mut command, descriptors, None, None);
    let capture = worker::run(
        command,
        Some(&bytes),
        1024,
        Duration::from_secs(300),
        credits,
        funding,
        None,
    )?;
    match capture.bytes.as_slice() {
        b"verified" => Ok(()),
        b"changed" => Err(SourceChanged.into()),
        _ => anyhow::bail!("Invalid held verification worker response"),
    }
}

/// Verify actual inherited member streams inside the watched process; false is a version mismatch, not success.
/// This worker-only helper does not start an account, claim authority or resolve a pathname.
#[doc(hidden)]
pub fn verify_held_worker(sources: &BTreeMap<PathBuf, (File, ContentDigest)>) -> Result<bool> {
    for (file, expected_version) in sources.values() {
        if let Err(error) = verify(HeldSource {
            file,
            expected_version,
        }) {
            if error.downcast_ref::<SourceChanged>().is_some() {
                return Ok(false);
            }
            return Err(error);
        }
    }
    Ok(true)
}

