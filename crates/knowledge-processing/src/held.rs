/// Read actual held chapter/media bytes in the RSS-watched worker, verifying the exact bytes passed to the encoder.
pub(crate) fn read_member(file: &File, version: &ContentDigest, limit: usize) -> Result<Vec<u8>> {
    let before = Stamp::read(file)?;
    ensure!(
        before.2 <= limit as u64,
        "EPUB member exceeds its format limit"
    );
    let bytes = crate::funding::read_fd(
        file,
        usize::try_from(before.2)?
            .checked_add(1)
            .context("EPUB member overflow")?,
    )?;
    ensure!(
        bytes.len() as u64 == before.2 && Stamp::read(file)? == before,
        SourceChanged
    );
    ensure!(
        format!("{:x}", Sha256::digest(&bytes)) == version.as_str(),
        SourceChanged
    );
    Ok(bytes)
}
