//! One process-owned effective policy over the SAME jobs account, not an executor or quota.
//!
//! Storage's accepted accounting policy governs defaults and lifetimes. Native facts and config
//! grant no source/cache access. Reserve before allocation/write; only actual settlement releases.
//! Lost holdings stay charged. Children must be reaped, runtimes/models destroyed and reader pins
//! ended before their trusted owner reports settlement. A worker finishing establishes none of those.
use crate::jobs::{
    Claim, JobError, Key, Limits, Queue, Reservation, Snapshot, Submission, Submitted,
};
use std::fmt;
use std::fs::File;
use std::sync::OnceLock;
use std::sync::atomic::{AtomicU32, Ordering};
mod native;

/// The only actual process owner; standalone Queue fixtures cannot mint process holdings.
static PROCESS: OnceLock<Account> = OnceLock::new();
/// Check inherited process state before touching an inherited queue lock or initialization cell.
static PROCESS_ID: AtomicU32 = AtomicU32::new(0);

/// Explicit configuration overrides; None selects the accepted native default, zero closes capacity.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Configuration {
    /// Working-memory ceiling in bytes, otherwise half the startup physical RAM.
    pub memory_bytes: Option<u64>,
    /// Further generated-storage ceiling; never overrides the required selected-volume floor.
    pub storage_bytes: Option<u64>,
}

/// Non-resource queue settings, not a second memory/storage policy or pool.
#[derive(Clone, Copy, Debug)]
pub struct Scheduling {
    /// Maximum queued work.
    pub max_pending: usize,
    /// Shared finite bound on submission receipts plus independent live resource holdings.
    pub max_records: usize,
    /// Maximum retained queue UTF-8 descriptor bytes.
    pub max_descriptor_bytes: usize,
    /// Concurrent unsettled executions per qualified mount.
    pub per_mount: usize,
}

/// Actual selected descriptor facts; no locality, ACL, placement or source-access grant.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Volume {
    /// Native filesystem device of the selected directory.
    pub device: u64,
    /// Native held-directory inode; no pathname re-resolution or fallback is used.
    pub directory: u64,
    /// Native volume capacity in bytes, converted with checked units.
    pub capacity_bytes: u64,
    /// Native bytes available to the current user, not total free blocks reserved for other users.
    pub available_bytes: u64,
    /// Required max(2 GiB, ceil(capacity/20)) retained free-space floor.
    pub floor_bytes: u64,
}
impl Volume {
    /// Available generated bytes above the required floor; a below-floor volume admits zero.
    fn spendable(self) -> u64 {
        self.available_bytes.saturating_sub(self.floor_bytes)
    }
}

/// Immutable effective startup facts, including the exact accepted overrides.
#[derive(Clone, Copy, Debug)]
pub struct Policy {
    /// Caller configuration, exposed rather than silently normalized away.
    pub configuration: Configuration,
    /// Observed startup physical RAM in bytes, not measured process memory or cgroup availability.
    pub physical_memory_bytes: u64,
    /// Effective whole process memory ceiling.
    pub memory_bytes: u64,
    /// Effective startup generated-storage ceiling, further constrained by every fresh observation.
    pub storage_bytes: u64,
    /// Actual selected volume at startup.
    pub startup_volume: Volume,
}

/// Contention is visible and distinct from a requirement larger than the whole effective ceiling.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Waiting {
    /// Current memory promises prevent admission; do not spin or classify as impossible.
    Memory,
    /// Current free-space/floor/outstanding promises prevent generated writes.
    Storage,
}

/// An actual reservation/growth result; waiting creates no partial reservation or hidden retry.
pub enum Decision<T> {
    /// All required accounting was acquired atomically before allocation/growth.
    Ready(T),
    /// Nothing was acquired; retain work in the host's existing bounded queue.
    Waiting(Waiting),
}

/// Fixed native status for later adapters; no existing wire DTO field or transport is invented.
#[derive(Clone, Copy, Debug)]
pub struct Status {
    /// Effective startup policy and actual overrides.
    pub policy: Policy,
    /// Fresh actual selected-volume observation.
    pub volume: Volume,
    /// SAME account total, including live resources independent of worker/mount execution.
    pub reserved: Reservation,
    /// Currently available memory after all promises.
    pub memory_available: u64,
    /// Currently available generated bytes after floor, ceiling and outstanding unwritten promises.
    pub storage_available: u64,
    /// Bounded resource holdings, including lost capabilities; no event history.
    pub holdings: usize,
    /// Original queue projection; its reserved field includes only unsettled execution-owned portions.
    pub queue: crate::jobs::Usage,
}

/// A real job's queue state plus its current resource wait without changing the frozen jobs enum.
#[derive(Clone, Copy, Debug)]
pub struct JobStatus {
    /// Unchanged native queue state, admitted intent and work maxima.
    pub queue: Snapshot,
    /// Current execution-owned portion; split child/runtime/model/pin charges live independently.
    pub execution: Reservation,
    /// Resource contention for queued work; None does not assert an available mount slot.
    pub waiting: Option<Waiting>,
}

/// Cost attribution before source verification never requires a fabricated content digest.
pub enum Origin<'a> {
    /// Process startup/runtime costs before source work.
    Startup,
    /// Native read/hash/inspection before verified source identity exists.
    BeforeVerification,
    /// Costs caused by a currently owned live claim; expected facts are checked, not authority.
    Job {
        /// Same account's current claim capability.
        claim: &'a Claim,
        /// Exact retained job facts.
        expected: Key<'a>,
    },
}

/// Typed refusals contain no input, native path, configuration secret or raw OS diagnostic.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Error {
    /// A process owner already exists; reconfiguration cannot reset live charges.
    AlreadyStarted,
    /// No startup policy was established.
    NotStarted,
    /// Inherited capabilities belong to a different process; never lock/reset them after fork.
    WrongProcess,
    /// Selected descriptor is not a current-user private directory.
    UnsafeDirectory,
    /// Native memory/volume facts were unavailable or inconsistent; no unlimited fallback.
    NativeFacts,
    /// Native unit/owned-account arithmetic could not be represented.
    Arithmetic,
    /// Native observation is not implemented on this platform.
    Unsupported,
    /// One required memory need exceeds the WHOLE effective memory limit, not just availability.
    TooLargeMemory,
    /// One generated-storage need exceeds the whole startup/configuration ceiling.
    TooLargeStorage,
    /// Finite shared accounting metadata is full; no new resource is admitted.
    Records,
    /// Missing/already settled holding, wrong claim ownership or invalid transfer amount.
    Stale,
    /// Ordinary frozen queue refusal, preserved without reinterpreting its transitions.
    Queue(JobError),
}
impl fmt::Display for Error {
    /// Write fixed classifications only.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "resource admission: {self:?}")
    }
}
impl std::error::Error for Error {}
impl From<JobError> for Error {
    /// Preserve the original queue classification without exposing submitted values.
    fn from(value: JobError) -> Self {
        Self::Queue(value)
    }
}

/// Only the process startup path constructs this owner; direct library hosts reuse current().
pub struct Account {
    /// Same native queue mutex and reserved counter, not an adapter-owned second pool.
    queue: Queue,
    /// Actual immutable startup policy, not a later mutable default.
    policy: Policy,
}

/// Non-cloneable resource capability independent of a per-mount execution slot.
/// Drop releases NOTHING: a lost handle may still have a live child/runtime/model/reader behind it.
/// The trusted owner must retain this capability and call finish only after actual resource settlement.
pub struct Holding {
    /// Exact same process accounting owner, retained while the capability exists.
    owner: Queue,
    /// Checked instance-lifetime identifier; no reset or reuse.
    id: u64,
}

/// One fixed-size resource record; no processor catalog, callback, strings or history.
pub(crate) struct Held {
    /// Checked same-account lifetime identity.
    id: u64,
    /// Causing job identity, retained even if execution metadata has been explicitly retired.
    origin: Option<u64>,
    /// Only synchronous claim-split loans may rejoin this exact original generation.
    generation: Option<u64>,
    /// Outstanding memory and unwritten storage promises.
    remaining: Reservation,
}

/// Native facts and bounded holding records INSIDE the existing queue's sole accounting mutex.
pub(crate) struct Extra {
    /// Held selected descriptor; no name fallback, shell probe or cache-location discovery.
    directory: File,
    /// Immutable effective policy.
    policy: Policy,
    /// Latest actual native observation, not an extra reservation counter.
    volume: Volume,
    /// Bounded live records; lost capabilities retain their charge and record.
    pub(crate) held: Vec<Held>,
}
impl Extra {
    /// Refresh exact held-directory/volume facts; do not reinterpret stale observation as available.
    pub(crate) fn refresh(&mut self) -> Result<(), Error> {
        let volume = native::volume(&self.directory)?;
        if volume.device != self.policy.startup_volume.device
            || volume.directory != self.policy.startup_volume.directory
        {
            return Err(Error::NativeFacts);
        }
        self.volume = volume;
        Ok(())
    }
    /// Fresh spendable ceiling before subtracting the SAME account's outstanding promises.
    pub(crate) fn ceiling(&self) -> u64 {
        // Anchor an override to actual startup free space, so consumed bytes reduce its
        // headroom too. A constant promise ceiling alone would replenish on every write.
        let floor = self.volume.floor_bytes.max(
            self.policy
                .startup_volume
                .available_bytes
                .saturating_sub(self.policy.storage_bytes),
        );
        self.policy
            .storage_bytes
            .min(self.volume.available_bytes.saturating_sub(floor))
    }
}

impl Account {
    /// Establish the one process owner before allocations, using an already admitted private directory.
    /// Overrides cannot exceed current volume/floor availability for storage; memory remains configurable.
    /// Returns native/typed errors honestly; a failed attempt publishes no usable alternate account.
    pub fn start(
        directory: File,
        configuration: Configuration,
        scheduling: Scheduling,
    ) -> Result<&'static Self, Error> {
        let pid = std::process::id();
        let prior = PROCESS_ID
            .compare_exchange(0, pid, Ordering::AcqRel, Ordering::Acquire)
            .unwrap_or_else(|p| p);
        if prior != 0 && prior != pid {
            return Err(Error::WrongProcess);
        }
        if PROCESS.get().is_some() {
            return Err(Error::AlreadyStarted);
        }
        let physical_memory_bytes = native::physical_memory()?;
        let volume = native::volume(&directory)?;
        let policy = Policy {
            configuration,
            physical_memory_bytes,
            memory_bytes: configuration
                .memory_bytes
                .unwrap_or(physical_memory_bytes / 2),
            storage_bytes: configuration
                .storage_bytes
                .unwrap_or(volume.spendable())
                .min(volume.spendable()),
            startup_volume: volume,
        };
        let mut queue = Queue::new(Limits {
            max_pending: scheduling.max_pending,
            max_records: scheduling.max_records,
            max_descriptor_bytes: scheduling.max_descriptor_bytes,
            per_mount: scheduling.per_mount,
            memory_bytes: policy.memory_bytes,
            temporary_bytes: policy.storage_bytes,
        })?;
        queue.1 = Some(pid);
        queue.lock()?.extra = Some(Extra {
            directory,
            policy,
            volume,
            held: Vec::new(),
        });
        PROCESS
            .set(Self { queue, policy })
            .map_err(|_| Error::AlreadyStarted)?;
        Self::current()
    }
    /// Reuse the existing process owner, never a per-library/new-empty replacement pool.
    pub fn current() -> Result<&'static Self, Error> {
        let pid = PROCESS_ID.load(Ordering::Acquire);
        if pid != 0 && pid != std::process::id() {
            return Err(Error::WrongProcess);
        }
        PROCESS.get().ok_or(Error::NotStarted)
    }
    /// Borrow the SAME queue; standalone Queue::new remains scoped cooperative accounting only.
    pub fn queue(&self) -> &Queue {
        &self.queue
    }
    /// Duplicate the actual selected generated-volume directory for a qualified native derived writer.
    /// This neither selects a new volume nor grants source/library authority; the caller pays descriptor costs.
    pub fn generated_directory(&self) -> Result<File, Error> {
        let i = self.queue.lock()?;
        i.extra
            .as_ref()
            .ok_or(Error::NotStarted)?
            .directory
            .try_clone()
            .map_err(|_| Error::NativeFacts)
    }
    /// Return visible startup configuration/native facts, not authority or physical enforcement.
    pub fn policy(&self) -> Policy {
        self.policy
    }
    /// Return fresh native availability and actual sole-account charges for later status/MCP mapping.
    pub fn status(&self) -> Result<Status, Error> {
        let mut i = self.queue.lock()?;
        i.extra.as_mut().ok_or(Error::NotStarted)?.refresh()?;
        let x = i.extra.as_ref().ok_or(Error::NotStarted)?;
        Ok(Status {
            policy: self.policy,
            volume: x.volume,
            reserved: i.reserved,
            memory_available: self
                .policy
                .memory_bytes
                .saturating_sub(i.reserved.memory_bytes),
            storage_available: x.ceiling().saturating_sub(i.reserved.temporary_bytes),
            holdings: x.held.len(),
            queue: i.usage(),
        })
    }
    /// Admit real verified-key jobs with a typed whole-budget refusal; ordinary intent semantics stay frozen.
    pub fn submit(&self, submission: Submission<'_>) -> Result<Submitted, Error> {
        too_large(submission.reservation, self.policy)?;
        Ok(self.queue.submit(submission)?)
    }
    /// Inspect actual queued contention without adding a state/tag to the frozen jobs API or wire DTO.
    pub fn job_status(&self, job: u64, expected: Key<'_>) -> Result<JobStatus, Error> {
        let mut i = self.queue.lock()?;
        let snapshot = i.inspect(job, expected)?;
        i.extra.as_mut().ok_or(Error::NotStarted)?.refresh()?;
        let waiting = if snapshot.state == crate::jobs::State::Queued {
            contention(&i, snapshot.reservation)
        } else {
            None
        };
        Ok(JobStatus {
            queue: snapshot,
            execution: i.job_resources(job),
            waiting,
        })
    }
    /// Reserve actual startup/pre-verification/job-caused concurrent costs BEFORE allocation.
    /// Waiting does not allocate a record or take partial resources; a lost Ready capability stays charged.
    pub fn reserve(
        &self,
        need: Reservation,
        origin: Origin<'_>,
    ) -> Result<Decision<Holding>, Error> {
        let mut i = self.queue.lock()?;
        let origin = match origin {
            Origin::Startup | Origin::BeforeVerification => None,
            Origin::Job { claim, expected } => {
                if !self.queue.owns(claim) {
                    return Err(Error::Stale);
                }
                i.claim_resources(claim, expected)?;
                Some(claim.job())
            }
        };
        too_large_add(attributed(&i, origin)?, need, self.policy)?;
        i.extra.as_mut().ok_or(Error::NotStarted)?.refresh()?;
        if let Some(reason) = contention(&i, need) {
            return Ok(Decision::Waiting(reason));
        }
        let id = next_record(&mut i)?;
        let total = plus(i.reserved, need)?;
        i.extra.as_mut().ok_or(Error::NotStarted)?.held.push(Held {
            id,
            origin,
            generation: None,
            remaining: need,
        });
        i.sequence = id;
        i.reserved = total;
        Ok(Decision::Ready(Holding {
            owner: self.queue.clone(),
            id,
        }))
    }
    /// Return a synchronous resource loan to the same still-live claim without freeing any charge.
    /// This supports repeated filesystem/Git phases; the parent still owns settlement responsibility.
    /// A stale/foreign claim or holding changes nothing and cannot release a possibly live resource.
    pub fn rejoin_claim(
        &self,
        holding: &mut Holding,
        claim: &Claim,
        expected: Key<'_>,
    ) -> Result<(), Error> {
        if !self.queue.owns(claim) || !holding.owner.owns(claim) {
            return Err(Error::Stale);
        }
        let mut i = self.queue.lock()?;
        let r = record(&i, holding.id)?;
        if r.origin != Some(claim.job()) || r.generation != Some(claim.generation_id()) {
            return Err(Error::Stale);
        }
        let amount = r.remaining;
        let total = plus(*i.claim_resources(claim, expected)?, amount)?;
        let x = i.extra.as_mut().ok_or(Error::NotStarted)?;
        let n = x
            .held
            .iter()
            .position(|r| r.id == holding.id)
            .ok_or(Error::Stale)?;
        x.held.remove(n);
        *i.claim_resources(claim, expected)? = total;
        Ok(())
    }

    /// Transfer part of a live claim to an independent resource lifetime atomically, with NO double charge/gap.
    /// After actual worker settlement the resource remains charged but no longer owns the mount execution slot.
    pub fn split_claim(
        &self,
        claim: &Claim,
        expected: Key<'_>,
        need: Reservation,
    ) -> Result<Holding, Error> {
        if !self.queue.owns(claim) {
            return Err(Error::Stale);
        }
        let mut i = self.queue.lock()?;
        let remaining = minus(*i.claim_resources(claim, expected)?, need)?;
        let id = next_record(&mut i)?;
        i.extra.as_mut().ok_or(Error::NotStarted)?.held.push(Held {
            id,
            origin: Some(claim.job()),
            generation: Some(claim.generation_id()),
            remaining: need,
        });
        *i.claim_resources(claim, expected)? = remaining;
        i.sequence = id;
        Ok(Holding {
            owner: self.queue.clone(),
            id,
        })
    }
}

impl Holding {
    /// Inspect this capability's remaining promises; missing/finished holdings return Stale.
    pub fn remaining(&self) -> Result<Reservation, Error> {
        let i = self.owner.lock()?;
        Ok(record(&i, self.id)?.remaining)
    }
    /// Acquire additional costs BEFORE allocation/growth in the same owner; waiting changes nothing.
    /// Check the complete causing-job need, not merely the delta, against the whole effective limits.
    pub fn grow(&mut self, additional: Reservation) -> Result<Decision<()>, Error> {
        let mut i = self.owner.lock()?;
        let r = record(&i, self.id)?;
        let origin = r.origin;
        let complete = if origin.is_some() {
            attributed(&i, origin)?
        } else {
            r.remaining
        };
        let policy = i.extra.as_ref().ok_or(Error::NotStarted)?.policy;
        too_large_add(complete, additional, policy)?;
        i.extra.as_mut().ok_or(Error::NotStarted)?.refresh()?;
        if let Some(reason) = contention(&i, additional) {
            return Ok(Decision::Waiting(reason));
        }
        let total = plus(i.reserved, additional)?;
        let x = i.extra.as_mut().ok_or(Error::NotStarted)?;
        let r = x
            .held
            .iter_mut()
            .find(|r| r.id == self.id)
            .ok_or(Error::Stale)?;
        r.remaining = plus(r.remaining, additional)?;
        i.reserved = total;
        Ok(Decision::Ready(()))
    }
    /// Reconcile bytes actually written on the selected volume AFTER the real writer completed that write.
    /// bytes is a newly confirmed delta, never a replay/cumulative count or an uncompleted write.
    /// Fresh native free space now accounts physical consumption; only the unwritten promise stays charged.
    /// Caller must bind the actual writer to this volume, bound writes first, and retain unknown/unfinished I/O.
    /// No deletion, publication, sync/power-loss guarantee, child stop or memory release occurs here.
    pub fn written(&mut self, bytes: u64) -> Result<Volume, Error> {
        let mut i = self.owner.lock()?;
        let amount = Reservation {
            memory_bytes: 0,
            temporary_bytes: bytes,
        };
        let remaining = minus(record(&i, self.id)?.remaining, amount)?;
        let total = minus(i.reserved, amount)?;
        let x = i.extra.as_mut().ok_or(Error::NotStarted)?;
        x.refresh()?;
        let volume = x.volume;
        x.held
            .iter_mut()
            .find(|r| r.id == self.id)
            .ok_or(Error::Stale)?
            .remaining = remaining;
        i.reserved = total;
        Ok(volume)
    }
    /// Release once ONLY after the trusted owner establishes real child/runtime/model/pin/I/O settlement.
    /// Drop, cancellation, worker completion and observation changes cannot substitute for this evidence.
    /// Already finished/lost capabilities do not release again; this performs no external cleanup itself.
    pub fn finish(&mut self) -> Result<(), Error> {
        let mut i = self.owner.lock()?;
        let total = minus(i.reserved, record(&i, self.id)?.remaining)?;
        let x = i.extra.as_mut().ok_or(Error::NotStarted)?;
        let n = x
            .held
            .iter()
            .position(|r| r.id == self.id)
            .ok_or(Error::Stale)?;
        x.held.remove(n);
        i.reserved = total;
        Ok(())
    }
}

/// Return only the same record, never adopt an unrelated lost holding by amount or source hash.
fn record(i: &crate::jobs::Inner, id: u64) -> Result<&Held, Error> {
    i.extra
        .as_ref()
        .ok_or(Error::NotStarted)?
        .held
        .iter()
        .find(|r| r.id == id)
        .ok_or(Error::Stale)
}
/// Bound live metadata jointly with submission receipts before any allocation; never reset identity.
fn next_record(i: &mut crate::jobs::Inner) -> Result<u64, Error> {
    let x = i.extra.as_ref().ok_or(Error::NotStarted)?;
    if i.usage()
        .records
        .checked_add(x.held.len())
        .ok_or(Error::Arithmetic)?
        >= i.limits.max_records
    {
        return Err(Error::Records);
    }
    let id = i.sequence.checked_add(1).ok_or(Error::Arithmetic)?;
    i.extra
        .as_mut()
        .ok_or(Error::NotStarted)?
        .held
        .try_reserve_exact(1)
        .map_err(|_| Error::Records)?;
    Ok(id)
}
/// Sum the causing job's current execution portion plus retained resources without a second counter.
fn attributed(i: &crate::jobs::Inner, origin: Option<u64>) -> Result<Reservation, Error> {
    let Some(job) = origin else {
        return Ok(Reservation {
            memory_bytes: 0,
            temporary_bytes: 0,
        });
    };
    i.extra
        .as_ref()
        .ok_or(Error::NotStarted)?
        .held
        .iter()
        .filter(|r| r.origin == Some(job))
        .try_fold(i.job_resources(job), |sum, r| plus(sum, r.remaining))
}
/// Classify impossible single-cost needs without confusing them with current availability.
fn too_large(need: Reservation, policy: Policy) -> Result<(), Error> {
    too_large_add(
        Reservation {
            memory_bytes: 0,
            temporary_bytes: 0,
        },
        need,
        policy,
    )
}
/// Overflowing aggregate costs also exceed every representable whole limit, never wait forever.
fn too_large_add(base: Reservation, delta: Reservation, policy: Policy) -> Result<(), Error> {
    if base
        .memory_bytes
        .checked_add(delta.memory_bytes)
        .is_none_or(|n| n > policy.memory_bytes)
    {
        return Err(Error::TooLargeMemory);
    }
    if base
        .temporary_bytes
        .checked_add(delta.temporary_bytes)
        .is_none_or(|n| n > policy.storage_bytes)
    {
        return Err(Error::TooLargeStorage);
    }
    Ok(())
}
/// Classify current contention after a fresh native volume observation.
fn contention(i: &crate::jobs::Inner, need: Reservation) -> Option<Waiting> {
    let x = i.extra.as_ref()?;
    waiting(
        need,
        i.limits
            .memory_bytes
            .saturating_sub(i.reserved.memory_bytes),
        x.ceiling().saturating_sub(i.reserved.temporary_bytes),
    )
}
/// Keep waiting reasons explicit; memory has stable precedence when both resources are unavailable.
fn waiting(need: Reservation, memory: u64, storage: u64) -> Option<Waiting> {
    if need.memory_bytes > memory {
        Some(Waiting::Memory)
    } else if need.temporary_bytes > storage {
        Some(Waiting::Storage)
    } else {
        None
    }
}
/// Checked addition before any state mutation; not physical allocation or work execution.
fn plus(a: Reservation, b: Reservation) -> Result<Reservation, Error> {
    Ok(Reservation {
        memory_bytes: a
            .memory_bytes
            .checked_add(b.memory_bytes)
            .ok_or(Error::Arithmetic)?,
        temporary_bytes: a
            .temporary_bytes
            .checked_add(b.temporary_bytes)
            .ok_or(Error::Arithmetic)?,
    })
}
/// Reject over-transfer/over-consumption before touching the sole account.
fn minus(a: Reservation, b: Reservation) -> Result<Reservation, Error> {
    Ok(Reservation {
        memory_bytes: a
            .memory_bytes
            .checked_sub(b.memory_bytes)
            .ok_or(Error::Stale)?,
        temporary_bytes: a
            .temporary_bytes
            .checked_sub(b.temporary_bytes)
            .ok_or(Error::Stale)?,
    })
}
